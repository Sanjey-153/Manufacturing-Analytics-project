"""
Maintenance Recommendation and Decision Support Module for Manufacturing Analytics.
Generates structured, domain-grounded maintenance recommendations based on model
predictions, failure probabilities, and operating parameter thresholds.
"""
from typing import Dict, Any, List


def determine_risk_level(failure_probability: float, threshold: float = 0.5) -> str:
    """
    Categorizes predicted failure probability into an operational risk tier.
    Note: Thresholds are operational heuristics based on model probability distribution
    and are not clinically/industrially certified hard standards.
    """
    if failure_probability < 0.20:
        return "Low"
    elif failure_probability < threshold:
        return "Moderate"
    elif failure_probability < 0.80:
        return "High"
    else:
        return "Critical"


def generate_maintenance_recommendation(
    predicted_class: int,
    failure_probability: float,
    input_data: Dict[str, Any],
    threshold: float = 0.5
) -> Dict[str, Any]:
    """
    Generates actionable maintenance guidance based on model prediction and sensor telemetry.
    """
    risk_level = determine_risk_level(failure_probability, threshold)
    
    diagnostic_flags: List[str] = []
    recommended_actions: List[str] = []

    # Extract sensor values for domain context checks
    air_temp = input_data.get("Air temperature [K]")
    proc_temp = input_data.get("Process temperature [K]")
    rot_speed = input_data.get("Rotational speed [rpm]")
    torque = input_data.get("Torque [Nm]")
    tool_wear = input_data.get("Tool wear [min]")
    machine_type = input_data.get("Type", "Unknown")

    # Diagnostic rule heuristics (based on Phase 3 EDA physical boundaries)
    if tool_wear is not None and tool_wear >= 200:
        diagnostic_flags.append(f"Elevated Tool Wear ({tool_wear:.1f} min >= 200 min threshold)")
        recommended_actions.append("Schedule tool insert replacement / inspect cutter wear land.")

    if torque is not None and torque >= 60.0:
        diagnostic_flags.append(f"High Spindle Torque ({torque:.1f} Nm >= 60.0 Nm limit)")
        recommended_actions.append("Inspect workpiece feed rate, depth of cut, and spindle mechanical loading.")
    elif torque is not None and torque <= 15.0:
        diagnostic_flags.append(f"Low Spindle Torque ({torque:.1f} Nm <= 15.0 Nm limit)")
        recommended_actions.append("Check spindle coupling and belt tension for slippage.")

    if air_temp is not None and proc_temp is not None:
        delta_t = proc_temp - air_temp
        if delta_t < 8.6:
            diagnostic_flags.append(f"Low Thermal Dissipation Gradient (Delta_T = {delta_t:.1f} K < 8.6 K)")
            recommended_actions.append("Inspect coolant flow rate, heat exchanger, and thermal dissipation paths.")

    if rot_speed is not None and (rot_speed < 1300 or rot_speed > 2200):
        diagnostic_flags.append(f"Spindle Speed Operating Outside Nominal Range ({rot_speed:.0f} rpm)")
        recommended_actions.append("Calibrate VFD spindle motor drive and check tachometer sensors.")

    # High-level summary recommendation
    if predicted_class == 0:
        if risk_level == "Low":
            summary = (
                "Machine is currently operating within normal parameters. "
                "Classified as Low Risk. Continue standard scheduled preventive monitoring."
            )
        else:
            summary = (
                "Machine is classified as Healthy under baseline threshold, but displays "
                "Moderate Risk indicators. Monitor operating telemetry closely on the next shift."
            )
    else:
        if risk_level == "Critical":
            summary = (
                "CRITICAL ALERT: Machine is classified as at immediate failure risk (>80% probability). "
                "Halt non-essential cutting cycles and conduct priority maintenance inspection."
            )
        else:
            summary = (
                "MAINTENANCE ALERT: Machine is classified as at risk of failure. "
                "Inspect tool wear, spindle mechanical torque, and thermal conditions before continued operation."
            )

    if not recommended_actions:
        recommended_actions.append("Maintain routine sensor telemetry logging and scheduled lubrication.")

    return {
        "predicted_class": int(predicted_class),
        "status_label": "Machine Failure" if predicted_class == 1 else "Healthy",
        "failure_probability": round(float(failure_probability), 4),
        "risk_level": risk_level,
        "classification_threshold": threshold,
        "summary": summary,
        "diagnostic_flags": diagnostic_flags,
        "recommended_actions": recommended_actions,
        "disclaimer": (
            "Decision-support guidance generated by machine learning predictive model. "
            "This prototype does not physically actuate machinery or replace certified plant safety protocols."
        )
    }
